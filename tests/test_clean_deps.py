"""Regression tests for dependency cleanup without removing real roles."""

import importlib.util
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location(
    "clean_deps", ROOT / "bin/clean-deps.py"
)
clean_deps = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(clean_deps)


class CleanDependenciesTests(unittest.TestCase):
    """Exercise real requirements and temporary Galaxy metadata."""

    def setUp(self):
        """Create isolated role directories and mock the removal command."""
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.roles = self.root / "roles"
        self.requirements = self.root / "requirements.yaml"
        self.requirements.write_text((ROOT / "requirements.yaml").read_text())
        removal = patch.object(clean_deps.subprocess, "run")
        self.remove = removal.start()
        self.addCleanup(removal.stop)

    def install(self, name, version, roles_path=None):
        """Write the metadata generated by ansible-galaxy role install."""
        path = (roles_path or self.roles) / name / "meta/.galaxy_install_info"
        path.parent.mkdir(parents=True)
        path.write_text(yaml.safe_dump({"version": version}))

    def clean(self, roles_paths=None):
        """Run cleanup against the temporary directories."""
        clean_deps.clean_dependencies(
            self.requirements, roles_paths or [self.roles]
        )

    def test_matching_versions_survive_comments_and_similar_names(self):
        """Keep roles that the old grep parser incorrectly removed."""
        for name, version in (
            ("geerlingguy.pip", "2.2.0"),
            ("geerlingguy.php", "6.1.0"),
            ("geerlingguy.php-versions", "7.2.0"),
            ("geerlingguy.apache", "4.0.0"),
            ("dj-wasabi.telegraf", "0.14.2"),
            ("paprikant.beacon", "2639596e9c0af8084272e60579ccddeb5a411bbf"),
        ):
            self.install(name, version)
        self.clean()
        self.remove.assert_not_called()

    def test_mismatch_removes_only_the_exact_role(self):
        """Remove an outdated pin while preserving a similarly named role."""
        self.install("geerlingguy.php", "6.0.0")
        self.install("geerlingguy.php-versions", "7.2.0")
        self.clean()
        self.remove.assert_called_once_with(
            [
                "ansible-galaxy",
                "role",
                "remove",
                "--roles-path",
                str(self.roles),
                "geerlingguy.php",
            ],
            check=True,
        )

    def test_unmanaged_and_repository_owned_roles_are_preserved(self):
        """Preserve roles outside requirements and roles without metadata."""
        self.install("local.custom", "1.0.0")
        path = self.roles / "geerlingguy.pip/meta"
        path.mkdir(parents=True)
        (path / "main.yml").write_text("---\n{}\n")
        self.clean()
        self.remove.assert_not_called()

    def test_unpinned_and_master_roles_are_preserved(self):
        """Keep the existing policy for floating dependencies."""
        self.install("paprikant.beacon-importer", None)
        self.install("galaxyproject.cvmfs", "old-commit")
        self.clean()
        self.remove.assert_not_called()

    def test_unknown_installed_version_is_preserved(self):
        """Avoid deleting a role when its installed version is unknown."""
        self.install("geerlingguy.pip", None)
        self.clean()
        self.remove.assert_not_called()

    def test_missing_roles_are_ignored(self):
        """Allow a fresh checkout with no installed dependencies."""
        self.clean()
        self.remove.assert_not_called()

    def test_removal_uses_the_path_containing_the_mismatched_role(self):
        """Preserve matching copies in other configured roles paths."""
        other_roles = self.root / "other roles"
        self.install("geerlingguy.pip", "2.2.0")
        self.install("geerlingguy.pip", "2.1.0", other_roles)
        self.clean([self.roles, other_roles])
        self.remove.assert_called_once_with(
            [
                "ansible-galaxy",
                "role",
                "remove",
                "--roles-path",
                str(other_roles),
                "geerlingguy.pip",
            ],
            check=True,
        )

    def test_removal_failure_is_reported(self):
        """Report errors when ansible-galaxy cannot remove a role."""
        self.install("geerlingguy.pip", "2.1.0")
        self.remove.side_effect = subprocess.CalledProcessError(1, "remove")
        with self.assertRaises(subprocess.CalledProcessError):
            self.clean()


if __name__ == "__main__":
    unittest.main()
